for v in ['irina', 'denis', 'dmitri', 'ruslan']:
    voice = PiperVoice.load(f'voices/ru_RU-{v}-medium.onnx')
    chunks = []
    for s in SENTENCES:
        b = io.BytesIO()
        with wave.open(b, 'wb') as w: voice.synthesize_wav(s, w)
        b.seek(0); w = wave.open(b)
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
